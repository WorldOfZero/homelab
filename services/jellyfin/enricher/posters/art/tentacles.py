"""Write tentacles.svg: a tentacle wrapping each corner of the poster and a larger one in the middle.

Each tentacle follows a curve whose bend tightens towards the tip, so it curls like a real one.
It is drawn as a tapering outline with suckers along the inside of the curl.

  python tentacles.py   # then render the poster with make_posters.py
"""

import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def centreline(x, y, heading, length, bend, curl, wave=0, loop=0, loop_at=0.4, loop_size=0.06, tip=3,
               steps=480):
    """Points along a curve that starts at (x, y) facing `heading` degrees (screen coordinates,
    0 = right, 90 = down) and turns by `bend` degrees over its length, plus `curl` degrees packed
    near the tip. `wave` sways it one way then back, for an S shape; `loop` turns it that many
    more degrees around `loop_at` (a fraction of the length), so 360 ties a loop, spread over
    `loop_size` of the length. A higher `tip` packs the curl closer to the tip. Negative angles turn
    anticlockwise."""
    points, angle = [], math.radians(heading)
    ds = length / steps
    total_bend, total_curl, sway = math.radians(bend), math.radians(curl), math.radians(wave)
    total_loop, spread = math.radians(loop), loop_size
    for i in range(steps + 1):
        t = i / steps
        points.append((x, y, angle, t))
        # d(angle)/dt: an even share of the bend, the curl growing as t^tip towards the tip, the
        # sway, and the loop as a bump around loop_at.
        knot = math.exp(-((t - loop_at) / spread) ** 2 / 2) / (spread * math.sqrt(2 * math.pi))
        angle += (total_bend + total_curl * (tip + 1) * t ** tip + sway * 2 * math.pi * math.cos(2 * math.pi * t)
                  + total_loop * knot) / steps
        x += math.cos(angle) * ds
        y += math.sin(angle) * ds
    return points


def tentacle(x, y, heading, length, width, bend, curl, suckers=True, **shape):
    pts = centreline(x, y, heading, length, bend, curl, **shape)
    half = [width / 2 * (1 - t) ** 0.85 + 1.5 for _, _, _, t in pts]
    left = [(px + math.sin(a) * h, py - math.cos(a) * h) for (px, py, a, _), h in zip(pts, half)]
    right = [(px - math.sin(a) * h, py + math.cos(a) * h) for (px, py, a, _), h in zip(pts, half)]
    outline = left + right[::-1]
    d = "M" + " L".join(f"{px:.1f} {py:.1f}" for px, py in outline) + " Z"
    out = [f'<path d="{d}"/>']
    if suckers:
        # On the inside of the curl: the right side for a clockwise turn, the left for anticlockwise.
        side = 1 if bend + curl > 0 else -1
        s, t_next = [], 0.06
        for (px, py, a, t), h in zip(pts, half):
            if t >= t_next and t < 0.88:
                r = h * 0.32
                cx, cy = px - side * math.sin(a) * h * 0.55, py + side * math.cos(a) * h * 0.55
                s.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}"/>')
                t_next = t + max(0.035, h * 2.6 / length)
        out.append(f'<g stroke-width="4" stroke-opacity="0.75">{"".join(s)}</g>')
    return "\n  ".join(out)


def main():
    parts = [
        # Top corners: each hangs from above the poster near a corner, swings out over the frame's
        # corner towards the side, and curls back at the tip.
        tentacle(250, -60, 110, 480, 80, 70, 260),          # top left
        tentacle(750, -60, 70, 480, 80, -70, -260),         # top right
        # Bottom corners: each rises from below the poster over the frame's corner, climbs the side
        # margin beside the title, and curls outward, clear of the title and label.
        tentacle(165, 1560, -100, 450, 66, 16, -250),       # bottom left
        tentacle(835, 1560, -80, 450, 66, -16, 250),        # bottom right
        # The middle one hangs from the top centre, swirls side to side on the way down without
        # crossing itself, and ends in a tight spiral above the label.
        tentacle(500, -60, 90, 1400, 130, -60, 540, wave=45, tip=11),
    ]
    with open(os.path.join(HERE, "tentacles.svg"), "w") as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1500">\n'
                "  <!-- Generated by tentacles.py; edit that and run it again. -->\n  "
                + "\n  ".join(parts) + "\n</svg>\n")


if __name__ == "__main__":
    main()
